// MinerPullResponse contains the remaining free and paid game allowances.
type MinerPullResponse struct {
	FreeTimesLeft int64 `json:"free_times_left"`
	BuyTimesLeft  int64 `json:"buy_times_left"`
	Price         int64 `json:"price"`
}

// GoldRecordResponse contains the account's usable gold balance.
type GoldRecordResponse struct {
	CanUsedCnt int64 `json:"can_used_cnt"`
}

// MinerMapItem is an object in the map returned when a game starts.
type MinerMapItem struct {
	ObjectType int     `json:"object_type"`
	X          float64 `json:"x"`
	Y          float64 `json:"y"`
	Rotation   float64 `json:"rotation"`
	Multiplier float64 `json:"multiplier"`
}

// MinerStartResponse preserves game and map IDs without floating-point conversion.
type MinerStartResponse struct {
	GameID string         `json:"game_id"`
	MapID  string         `json:"map_id"`
	Items  []MinerMapItem `json:"items"`
}

// MinerReward describes the result of reporting a map object.
type MinerReward struct {
	Kind       int    `json:"reward_kind"`
	Size       int64  `json:"size"`
	ObjectID   int    `json:"object_id"`
	Origin     *int64 `json:"origin,omitempty"`
	ExpireDay  *int64 `json:"expire_day,omitempty"`
	ReasonCode *int64 `json:"reason_code,omitempty"`
}

// MinerGetItemResponse contains an optional reward; a null result grants none.
type MinerGetItemResponse struct {
	Reward *MinerReward `json:"reward,omitempty"`
}

// MinerFinishResponse contains the allowances after a game has finished.
type MinerFinishResponse MinerPullResponse

// MinerQueryVideoResponse preserves the poll's data without inferring native
// ad completion. Tools/time poll data has no schema consumed by the H5; extra
// reward data contains reward_kind and size. JSON null represents pending data.
type MinerQueryVideoResponse struct {
	Data json.RawMessage `json:"data"`
}

// MinerPuzzleQueryResponse contains puzzle availability and the complete H5
// data (including puzzles, end_time and reward when present).
type MinerPuzzleQueryResponse struct {
	CanReceive bool            `json:"can_receive"`
	Data       json.RawMessage `json:"data"`
}

// MinerPull reads the Gold Miner game's remaining allowances.
func (c *Client) MinerPull(ctx context.Context) (*MinerPullResponse, error) {
	const op = "minerPull"
	data, err := c.minerH5GET(ctx, op, "/rest/1.0/imact/miner/pull", nil)
	if err != nil {
		return nil, err
	}
	status, err := decodeMinerStatus(data)
	return status, wrapErr(op, err)
}

// GoldRecord reads usable gold through the app's Gold Miner H5 contract.
func (c *Client) GoldRecord(ctx context.Context) (*GoldRecordResponse, error) {
	const op = "goldRecord"
	data, err := c.minerH5GET(ctx, op, "/rest/1.0/inte/system/getrecord", nil)
	if err != nil {
		return nil, err
	}
	fields, err := minerObject(data)
	if err != nil {
		return nil, wrapErr(op, err)
	}
	value, err := minerInteger(fields["can_used_cnt"])
	if err != nil || value < 0 {
		return nil, wrapErr(op, errors.New("invalid can_used_cnt"))
	}
	return &GoldRecordResponse{CanUsedCnt: value}, nil
}

// MinerStart starts one game. It never retries a request with an uncertain outcome.
func (c *Client) MinerStart(ctx context.Context) (*MinerStartResponse, error) {
	const op = "minerStart"
	data, err := c.minerH5GET(ctx, op, "/rest/1.0/imact/miner/start", nil)
	if err != nil {
		return nil, err
	}
	result, err := decodeMinerStart(data)
	return result, wrapErr(op, err)
}

// MinerGetItem reports one object with the three fields sent by the official H5.
// reportID is the decimal millisecond timestamp generated by the game client.
func (c *Client) MinerGetItem(ctx context.Context, gameID string, objectType int, reportID string) (*MinerGetItemResponse, error) {
	const op = "minerGetItem"
	if !validMinerID(gameID) || objectType <= 0 || !validMinerDecimal(reportID) {
		return nil, wrapErr(op, errors.New("invalid game ID, object type or report ID"))
	}
	query := url.Values{"game_id": {gameID}, "object_type": {strconv.Itoa(objectType)}, "report_id": {reportID}}
	data, err := c.minerH5GET(ctx, op, "/rest/1.0/imact/miner/getitem", query)
	if err != nil {
		return nil, err
	}
	result, err := decodeMinerReward(data)
	return result, wrapErr(op, err)
}

// MinerFinish finishes one game with the APK's getRand native bridge signature.
// It sends one request and does not try alternate parameter combinations.
func (c *Client) MinerFinish(ctx context.Context, gameID string) (*MinerFinishResponse, error) {
	const op = "minerFinish"
	if !validMinerID(gameID) {
		return nil, wrapErr(op, errors.New("invalid game ID"))
	}
	if err := c.requireAndroidApp(); err != nil {
		return nil, wrapErr(op, err)
	}
	profile := *c.AndroidAppProfile()
	timestamp := c.androidAppTime()
	rand, err := c.androidH5Rand(profile, timestamp)
	if err != nil {
		return nil, wrapErr(op, err)
	}
	query := url.Values{"game_id": {gameID}, "devuid": {profile.DeviceID}, "cuid": {profile.DeviceID},
		"version": {profile.Version}, "clienttype": {strconv.Itoa(profile.ClientType)},
		"lang": {profile.Language}, "channel": {profile.UserAgent},
		"time": {strconv.FormatInt(timestamp, 10)}, "rand": {rand}, "zid": {""}}
	data, err := c.minerH5GET(ctx, op, "/rest/1.0/imact/miner/finishgame", query)
	if err != nil {
		return nil, err
	}
	status, err := decodeMinerStatus(data)
	if err != nil {
		return nil, wrapErr(op, err)
	}
	return (*MinerFinishResponse)(status), nil
}

// MinerQueryVideo performs one video-result poll. The official app invokes it
// after showSignInRewardAd reports isSuccess; this method does not perform that
// native operation or establish that an ad completed. Types are 0 (tool),
// 1 (extra time) and 2 (extra reward). Only type 0 takes an objectID.
func (c *Client) MinerQueryVideo(ctx context.Context, gameID string, videoType int, objectID *int) (*MinerQueryVideoResponse, error) {
	const op = "minerQueryVideo"
	if !validMinerID(gameID) || videoType < 0 || videoType > 2 ||
		(videoType == 0 && (objectID == nil || *objectID <= 0)) || (videoType != 0 && objectID != nil) {
		return nil, wrapErr(op, errors.New("invalid game ID, video type or object ID"))
	}
	query := url.Values{"game_id": {gameID}, "video_type": {strconv.Itoa(videoType)}}
	if objectID != nil {
		query.Set("object_id", strconv.Itoa(*objectID))
	}
	data, err := c.minerH5Request(ctx, op, "/rest/1.0/imact/miner/queryvideo", query, true)
	if err != nil {
		return nil, err
	}
	return &MinerQueryVideoResponse{Data: data}, nil
}

// MinerPuzzleQuery reads puzzle state. It does not receive or redeem rewards.
func (c *Client) MinerPuzzleQuery(ctx context.Context) (*MinerPuzzleQueryResponse, error) {
	const op = "minerPuzzleQuery"
	data, err := c.minerH5GET(ctx, op, "/rest/1.0/imact/puzzle/query", nil)
	if err != nil {
		return nil, err
	}
	fields, err := minerObject(data)
	if err != nil {
		return nil, wrapErr(op, err)
	}
	var canReceive bool
	if raw, exists := fields["can_receive"]; !exists {
		return nil, wrapErr(op, errors.New("puzzle data is missing can_receive"))
	} else if err := json.Unmarshal(raw, &canReceive); err != nil || bytes.Equal(bytes.TrimSpace(raw), []byte("null")) {
		value, err := minerInteger(raw)
		if err != nil || (value != 0 && value != 1) {
			return nil, wrapErr(op, errors.New("invalid puzzle can_receive"))
		}
		canReceive = value == 1
	}
	return &MinerPuzzleQueryResponse{CanReceive: canReceive, Data: data}, nil
}

// The H5 API uses the WebView's cookie session. Applying androidAppAPIRequest
// here would inject native Retrofit fields that are absent from the game bundle.
func (c *Client) minerH5GET(ctx context.Context, op, path string, query url.Values) (json.RawMessage, error) {
	return c.minerH5Request(ctx, op, path, query, false)
}

func (c *Client) minerH5Request(ctx context.Context, op, path string, query url.Values, pollData bool) (json.RawMessage, error) {
	if err := c.requireAndroidApp(); err != nil {
		return nil, wrapErr(op, err)
	}
	host, _ := c.snapshot()
	req, err := c.newRequest(ctx, &requestOpts{method: http.MethodGet, path: path, query: query,
		headers: map[string]string{"Content-Type": "application/x-www-form-urlencoded",
			"X-Requested-With": "XMLHttpRequest", "Accept": "application/json, text/plain, */*",
			"Referer": strings.TrimRight(host, "/") + "/wap/glodminer?show_type=3"}})
	if err != nil {
		return nil, wrapErr(op, errors.New("invalid Gold Miner request"))
	}
	resp, err := c.doHTTP(req, c.timeout)
	if err != nil {
		return nil, wrapErr(op, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, wrapErr(op, &httpStatusError{StatusCode: resp.StatusCode})
	}
	const maximum = 4 << 20
	body, err := io.ReadAll(io.LimitReader(resp.Body, maximum+1))
	if err != nil {
		return nil, wrapErr(op, err)
	}
	if len(body) > maximum {
		return nil, wrapErr(op, errors.New("Gold Miner response exceeds size limit"))
	}
	data, err := decodeMinerEnvelope(body, pollData)
	if err != nil {
		return nil, wrapErr(op, err)
	}
	c.mergeCookies(resp.Cookies())
	return data, nil
}

func decodeMinerEnvelope(body []byte, pollData bool) (json.RawMessage, error) {
	fields, err := minerObject(body)
	if err != nil {
		return nil, errors.New("invalid Gold Miner response envelope")
	}
	found, code := false, int64(0)
	for _, name := range []string{"errno", "code", "error_code"} {
		value, ok := fields[name]
		if !ok {
			continue
		}
		parsed, err := minerInteger(value)
		if err != nil || int64(int(parsed)) != parsed || (found && parsed != code) {
			return nil, errors.New("invalid or conflicting Gold Miner result code")
		}
		found, code = true, parsed
	}
	if !found {
		return nil, errors.New("Gold Miner response is missing its result code")
	}
	if code != 0 {
		// Server messages can echo cookies and signed request URLs. Preserve the
		// stable numeric code without putting untrusted response text in logs.
		return nil, &APIError{Code: int(code)}
	}
	data, exists := fields["data"]
	if !exists || !json.Valid(data) {
		return nil, errors.New("Gold Miner response is missing valid data")
	}
	if _, err := minerObject(data); !pollData && err != nil {
		return nil, errors.New("Gold Miner response is missing valid data")
	}
	return data, nil
}

func decodeMinerStatus(data []byte) (*MinerPullResponse, error) {
	fields, err := minerObject(data)
	if err != nil {
		return nil, err
	}
	result := &MinerPullResponse{}
	for _, field := range []struct {
		name string
		out  *int64
	}{{"free_times_left", &result.FreeTimesLeft}, {"buy_times_left", &result.BuyTimesLeft}, {"price", &result.Price}} {
		value, err := minerInteger(fields[field.name])
		if err != nil || value < 0 {
			return nil, errors.New("invalid Gold Miner allowance or price")
		}
		*field.out = value
	}
	return result, nil
}

func decodeMinerStart(data []byte) (*MinerStartResponse, error) {
	fields, err := minerObject(data)
	if err != nil {
		return nil, err
	}
	gameID, err := minerID(fields["game_id"])
	if err != nil {
		return nil, errors.New("invalid game_id")
	}
	mapID, err := minerID(fields["map_id"])
	if err != nil {
		return nil, errors.New("invalid map_id")
	}
	mapInfo, err := minerObject(fields["map_info"])
	if err != nil {
		return nil, errors.New("invalid map_info")
	}
	var items []json.RawMessage
	if err := json.Unmarshal(mapInfo["items"], &items); err != nil || bytes.Equal(bytes.TrimSpace(mapInfo["items"]), []byte("null")) {
		return nil, errors.New("invalid map_info.items")
	}
	result := &MinerStartResponse{GameID: gameID, MapID: mapID, Items: make([]MinerMapItem, 0, len(items))}
	for _, raw := range items {
		item, err := minerObject(raw)
		if err != nil {
			return nil, errors.New("invalid map object")
		}
		objectType, err := minerInteger(item["object_type"])
		if err != nil || objectType < 0 || int64(int(objectType)) != objectType {
			return nil, errors.New("invalid map object_type")
		}
		entry := MinerMapItem{ObjectType: int(objectType)}
		for _, field := range []struct {
			name string
			out  *float64
		}{{"x", &entry.X}, {"y", &entry.Y}, {"rotation", &entry.Rotation}, {"multiplier", &entry.Multiplier}} {
			value, err := minerFloat(item[field.name])
			if err != nil {
				return nil, errors.New("invalid map object coordinates or multiplier")
			}
			*field.out = value
		}
		result.Items = append(result.Items, entry)
	}
	return result, nil
}

func decodeMinerReward(data []byte) (*MinerGetItemResponse, error) {
	fields, err := minerObject(data)
	if err != nil {
		return nil, err
	}
	raw, exists := fields["result"]
	if !exists {
		return nil, errors.New("Gold Miner item data is missing result")
	}
	if bytes.Equal(bytes.TrimSpace(raw), []byte("null")) {
		return &MinerGetItemResponse{}, nil
	}
	reward, err := minerObject(raw)
	if err != nil {
		return nil, errors.New("invalid Gold Miner reward")
	}
	kind, err := minerInteger(reward["reward_kind"])
	if err != nil || kind < 0 || int64(int(kind)) != kind {
		return nil, errors.New("invalid Gold Miner reward_kind")
	}
	var size int64
	if raw, exists := reward["size"]; exists {
		size, err = minerInteger(raw)
		if err != nil || size < 0 {
			return nil, errors.New("invalid Gold Miner reward size")
		}
	} else if kind != 100 && kind != 10 {
		return nil, errors.New("Gold Miner reward is missing size")
	}
	result := &MinerReward{Kind: int(kind), Size: size}
	if raw, exists := reward["object_id"]; exists {
		id, err := minerInteger(raw)
		if err != nil || id < 0 || int64(int(id)) != id {
			return nil, errors.New("invalid Gold Miner reward object_id")
		}
		result.ObjectID = int(id)
	} else if kind == 100 || kind == 10 {
		return nil, errors.New("Gold Miner tool reward is missing object_id")
	}
	for _, field := range []struct {
		name string
		out  **int64
	}{{"origin", &result.Origin}, {"expire_day", &result.ExpireDay}, {"reason_code", &result.ReasonCode}} {
		if raw, exists := reward[field.name]; exists && !bytes.Equal(bytes.TrimSpace(raw), []byte("null")) {
			value, err := minerInteger(raw)
			if err != nil {
				return nil, errors.New("invalid Gold Miner reward metadata")
			}
			*field.out = &value
		}
	}
	return &MinerGetItemResponse{Reward: result}, nil
}

func minerObject(data []byte) (map[string]json.RawMessage, error) {
	var result map[string]json.RawMessage
	if err := json.Unmarshal(data, &result); err != nil || result == nil {
		return nil, errors.New("invalid Gold Miner JSON object")
	}
	return result, nil
}

func minerNumber(data []byte) (string, error) {
	text := strings.TrimSpace(string(data))
	if strings.HasPrefix(text, `"`) {
		if err := json.Unmarshal(data, &text); err != nil {
			return "", errors.New("invalid numeric value")
		}
	}
	if text == "" || strings.TrimSpace(text) != text {
		return "", errors.New("missing numeric value")
	}
	return text, nil
}

func minerInteger(data []byte) (int64, error) {
	text, err := minerNumber(data)
	if err != nil {
		return 0, err
	}
	value, err := strconv.ParseInt(text, 10, 64)
	if err != nil {
		return 0, errors.New("invalid integer value")
	}
	return value, nil
}

func minerFloat(data []byte) (float64, error) {
	text, err := minerNumber(data)
	if err != nil {
		return 0, err
	}
	value, err := strconv.ParseFloat(text, 64)
	if err != nil || math.IsNaN(value) || math.IsInf(value, 0) {
		return 0, errors.New("invalid finite numeric value")
	}
	return value, nil
}

func minerID(data []byte) (string, error) {
	text := strings.TrimSpace(string(data))
	if strings.HasPrefix(text, `"`) {
		if err := json.Unmarshal(data, &text); err != nil || !validMinerID(text) {
			return "", errors.New("invalid identifier")
		}
		return text, nil
	}
	if !validMinerDecimal(text) {
		return "", errors.New("invalid identifier")
	}
	return text, nil
}

func validMinerID(text string) bool {
	if text == "" || len(text) > 256 {
		return false
	}
	for _, c := range text {
		if !((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '-' || c == '_') {
			return false
		}
	}
	return true
}

func validMinerDecimal(text string) bool {
	if text == "" || len(text) > 256 {
		return false
	}
	for _, c := range text {
		if c < '0' || c > '9' {
			return false
		}
	}
	return true
}
